#!/bin/bash

# Project   : Monitoring Free Disk Space & Sending Email Alerts
# Description: Checks disk usage on all mounted filesystems and
#               sends an email alert when usage exceeds threshold.


# ─── CONFIGURATION ────────────────────────────────────────────
THRESHOLD=80                              # Alert if usage >= this %
CRITICAL_THRESHOLD=90                     # Critical alert level %
EMAIL_TO="admin@example.com"              # Recipient email address
EMAIL_FROM="diskmonitor@$(hostname)"      # Sender address
LOG_FILE="/var/log/disk_monitor.log"      # Log file path
ALERT_LOG="/var/log/disk_alerts.log"      # Alert-only log
REPORT_FILE="/tmp/disk_report_$(date '+%Y%m%d_%H%M%S').txt"
DATE=$(date '+%Y-%m-%d %H:%M:%S')
HOSTNAME=$(hostname)

# Filesystems to SKIP (space-separated)
SKIP_FS="tmpfs devtmpfs udev squashfs overlay"

# ─── FUNCTIONS ────────────────────────────────────────────────

log_info() {
    echo "[$DATE] [INFO]  $1" >> "$LOG_FILE"
}

log_warn() {
    echo "[$DATE] [WARN]  $1" | tee -a "$LOG_FILE" | tee -a "$ALERT_LOG"
}

log_critical() {
    echo "[$DATE] [CRIT]  $1" | tee -a "$LOG_FILE" | tee -a "$ALERT_LOG"
}

should_skip() {
    FS_TYPE=$1
    for SKIP in $SKIP_FS; do
        [ "$FS_TYPE" = "$SKIP" ] && return 0
    done
    return 1
}

send_email_alert() {
    local SUBJECT="$1"
    local BODY="$2"

    if command -v sendmail &>/dev/null; then
        {
            echo "To: $EMAIL_TO"
            echo "From: $EMAIL_FROM"
            echo "Subject: $SUBJECT"
            echo "MIME-Version: 1.0"
            echo "Content-Type: text/plain"
            echo ""
            echo "$BODY"
        } | sendmail -t
        log_info "Email alert sent to $EMAIL_TO — Subject: $SUBJECT"

    elif command -v mail &>/dev/null; then
        echo "$BODY" | mail -s "$SUBJECT" -r "$EMAIL_FROM" "$EMAIL_TO"
        log_info "Email alert sent via 'mail' to $EMAIL_TO"

    else
        log_warn "No mail utility found (sendmail/mail). Email not sent."
        log_warn "Install with: sudo apt install mailutils"
    fi
}

print_banner() {
    echo "=============================================="
    echo "   Disk Space Monitor — Host: $HOSTNAME"
    echo "   Date : $DATE"
    echo "   Alert Threshold  : ${THRESHOLD}%"
    echo "   Critical Threshold: ${CRITICAL_THRESHOLD}%"
    echo "=============================================="
    echo ""
}

build_report() {
    local ALERTS=$1
    cat <<EOF
===== DISK SPACE REPORT =====
Host     : $HOSTNAME
Date     : $DATE
Threshold: $THRESHOLD% (Critical: $CRITICAL_THRESHOLD%)

Filesystem Summary:
$(df -h | grep -vE "^Filesystem" | grep -vE "$(echo "$SKIP_FS" | tr ' ' '|')")

Partitions Exceeding Threshold:
$ALERTS

--- Generated by disk_monitor.sh ---
EOF
}

# ─── MAIN CHECK ───────────────────────────────────────────────
check_disk_space() {
    local HAS_ALERT=0
    local ALERT_SUMMARY=""
    local EMAIL_BODY=""

    print_banner

    printf "  %-35s %-8s %-8s %-8s %-6s %s\n" \
        "Filesystem" "Size" "Used" "Avail" "Use%" "Mounted On"
    echo "  -----------------------------------------------------------------------"

    # Read df output (skip header)
    while IFS= read -r line; do
        # Extract fields
        FS=$(echo "$line"         | awk '{print $1}')
        SIZE=$(echo "$line"       | awk '{print $2}')
        USED=$(echo "$line"       | awk '{print $3}')
        AVAIL=$(echo "$line"      | awk '{print $4}')
        USE_PCT=$(echo "$line"    | awk '{print $5}' | tr -d '%')
        MOUNT=$(echo "$line"      | awk '{print $6}')
        FS_TYPE=$(df -T "$MOUNT" 2>/dev/null | awk 'NR==2{print $2}')

        # Skip unwanted filesystem types
        should_skip "$FS_TYPE" && continue

        # Determine status indicator
        if [ "$USE_PCT" -ge "$CRITICAL_THRESHOLD" ] 2>/dev/null; then
            STATUS="CRITICAL"
            HAS_ALERT=1
            MSG="CRITICAL: $MOUNT on $HOSTNAME is at ${USE_PCT}% (${USED}/${SIZE})"
            ALERT_SUMMARY+="  [CRITICAL] $MOUNT — ${USE_PCT}% used\n"
            log_critical "$MSG"
        elif [ "$USE_PCT" -ge "$THRESHOLD" ] 2>/dev/null; then
            STATUS=" WARNING "
            HAS_ALERT=1
            MSG="WARNING: $MOUNT on $HOSTNAME is at ${USE_PCT}% (${USED}/${SIZE})"
            ALERT_SUMMARY+="  [WARNING]  $MOUNT — ${USE_PCT}% used\n"
            log_warn "$MSG"
        else
            STATUS=" OK      "
            log_info "OK: $MOUNT is at ${USE_PCT}% (${USED}/${SIZE})"
        fi

        printf "  %-35s %-8s %-8s %-8s %-6s %s  %s\n" \
            "$FS" "$SIZE" "$USED" "$AVAIL" "${USE_PCT}%" "$MOUNT" "$STATUS"

    done < <(df -h | tail -n +2)

    echo ""

    # ── Send email if any threshold breached ──────────────────
    if [ "$HAS_ALERT" -eq 1 ]; then
        echo " Alert(s) detected! Sending email to $EMAIL_TO..."
        EMAIL_BODY=$(build_report "$ALERT_SUMMARY")
        send_email_alert " Disk Space Alert on $HOSTNAME — $(date '+%Y-%m-%d')" "$EMAIL_BODY"
        echo "$EMAIL_BODY" > "$REPORT_FILE"
        echo "  Report saved: $REPORT_FILE"
    else
        echo " All filesystems are within acceptable limits."
        log_info "All filesystems OK."
    fi

    echo ""
    echo "=============================================="
}

# ─── MAIN ─────────────────────────────────────────────────────
main() {
    mkdir -p "$(dirname "$LOG_FILE")" 2>/dev/null
    check_disk_space
    log_info "Disk check completed."
}

main
